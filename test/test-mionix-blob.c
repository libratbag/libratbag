/*
 * Unit tests for the Mionix Castor profile blob codec.
 *
 * The codec is deliberately free of libratbag types and of I/O so that it can
 * be checked against frames the hardware has actually accepted, with no device
 * present. The three blobs below are real captures, embedded verbatim:
 *
 *  - blob_red / blob_green: consecutive SET_FEATURE frames the vendor's own
 *    Windows software sent while the wheel and logo LEDs were changed from red
 *    to green. They differ in exactly four bytes, and re-deriving one from the
 *    other is what proves an encode is a frame the device accepts.
 *  - blob_read: the device's own reply to 0x60/0x07 for profile 0, i.e. a
 *    profile as the firmware hands it back.
 *
 * Captured with the rig in https://github.com/fawaz7/castty
 * (research/tools/, frames under research/captures/).
 */

